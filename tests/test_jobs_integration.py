def test_commercial_delivery_retains_required_source_and_music_credits(tmp_path):
    args, state_dir, source, music = fixture_job(tmp_path)
    state = catalogue.read(state_dir / "catalogue.json")
    credits = {str(p): "Original fixture by Test Owner: " + p.name for p in (source, music)}
    state["permissions"] = {catalogue.sha256(p): catalogue.permission_grant(
        "Generated and owned by this test", mode="commercial", credit=credits[str(p)],
        license="Owned test fixture: commercial adaptation and distribution authorized",
        rights_verified_by="Integration test fixture author", rights_verified_at="2026-10-30T00:00:00Z",
        commercial_use=True, adaptation=True, distribution=True, monetization=True,
        attribution_required=True) for p in (source, music)}
    catalogue.save(state_dir / "catalogue.json", state)
    assert jobs.main(args + ["--mode", "commercial"]) == 0
    _, manifest = job_state(tmp_path)
    rendered = Path(manifest["delivery"]["video"]).parent
    metadata = catalogue.read(rendered / "youtube_metadata.json")
    assert set(metadata["source_credits"]) == set(credits.values())
    assert all(credit in metadata["description"] for credit in credits.values())
    rights = catalogue.read(rendered / "rights_report.json")
    assert rights["mode"] == "commercial" and not rights["independent_ownership_verification"]
    assert {r["path"] for r in rights["sources"]} == set(credits)
    assert all(r["permission"]["credit"] == credits[r["path"]] for r in rights["sources"])
    assert not manifest["delivery"]["monetizable"]


def test_resume_rejects_music_consumed_by_another_job_during_interruption(tmp_path, monkeypatch):
    args, state_dir, _, music = fixture_job(tmp_path)
    def interrupt(*unused):
        raise KeyboardInterrupt("Test interruption before render")
    monkeypatch.setattr(jobs, "_render", interrupt)
    assert jobs.main(args) == 130
    path, manifest = job_state(tmp_path)
    state = catalogue.read(state_dir / "catalogue.json")
    row = state["media"][str(music)]
    state["used"].append(dict(title=row["title"], family=catalogue.family(row["title"]),
                              sha256=row["sha256"], job_id="other-completed-job"))
    catalogue.save(state_dir / "catalogue.json", state)
    def must_not_render(*unused):
        pytest.fail("Music already consumed by another job must not render again")
    monkeypatch.setattr(jobs, "_render", must_not_render)
    assert jobs.main(["resume", str(path)]) == 2
    failed = catalogue.read(path / "manifest.json")
    assert failed["status"] == "BLOCKED" and not failed.get("delivery")
    assert len(catalogue.read(state_dir / "catalogue.json")["used"]) == 1


def test_interruption_after_delivery_does_not_bypass_foreign_music_usage(tmp_path, monkeypatch):
    args, state_dir, _, music = fixture_job(tmp_path)
    consume = jobs._consume
    def interrupt(*unused):
        raise KeyboardInterrupt("Test interruption between delivery and catalogue usage")
    monkeypatch.setattr(jobs, "_consume", interrupt)
    assert jobs.main(args) == 130
    path, manifest = job_state(tmp_path)
    assert manifest["status"] == "INTERRUPTED" and manifest["delivery"]
    state = catalogue.read(state_dir / "catalogue.json")
    assert not state["used"]
    row = state["media"][str(music)]
    state["used"].append(dict(title=row["title"], family=catalogue.family(row["title"]),
                              sha256=row["sha256"], job_id="other-completed-job"))
    catalogue.save(state_dir / "catalogue.json", state)
    monkeypatch.setattr(jobs, "_consume", consume)
    assert jobs.main(["resume", str(path)]) == 2
    assert catalogue.read(path / "manifest.json")["status"] == "BLOCKED"
    assert len(catalogue.read(state_dir / "catalogue.json")["used"]) == 1
    assert catalogue.sha256(Path(manifest["delivery"]["video"])) == manifest["delivery"]["sha256"]
