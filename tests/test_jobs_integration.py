def test_live_previous_process_prevents_duplicate_stage(tmp_path):
    job = jobs.Job(tmp_path / "job", options={})
    child = subprocess.Popen([sys.executable, "-c", "import time; time.sleep(30)"],
                             start_new_session=True)
    try:
        job.state["stages"]["render"] = dict(status="INTERRUPTED", attempts=1,
                                             process_groups=[child.pid])
        job.save()
        with pytest.raises(UltraError, match="still running; no duplicate started"):
            job.stage("render", lambda: pytest.fail("A second encoder must not start"))
        assert job.state["stages"]["render"]["attempts"] == 1
    finally:
        child.terminate()
        child.wait(timeout=5)
    result = job.stage("render", lambda: dict(artifacts=[], resumed=True))
    assert result["resumed"] and job.state["stages"]["render"]["attempts"] == 2


def test_authorized_remote_music_is_acquired_one_shot_with_http_only_simulated(tmp_path, monkeypatch):
    from youtube_edit_ultra import media
    args, state_dir, _, song = fixture_job(tmp_path)
    remote = tmp_path / "http-fixture.wav"
    song.rename(remote)  # Only this generated fixture moves outside the scanned input library.
    url = "https://fixtures.invalid/owned-song.wav"
    state = catalogue.read(state_dir / "catalogue.json")
    state["authorized_urls"] = [dict(
        url=url, kind="audio", style="reggaeton", title="Original Test Song", artist="Fixture Artist",
        **catalogue.permission_grant("Owned synthetic HTTP fixture; transport simulated in test"))]
    catalogue.save(state_dir / "catalogue.json", state)
    requests = []
    actual_run = media.run
    def http_boundary(command, **kwargs):
        if command[0] == "curl":
            assert command[-1] == url
            destination = Path(command[command.index("--output") + 1])
            shutil.copyfile(remote, destination)
            requests.append(url)
            return ""
        return actual_run(command, **kwargs)
    monkeypatch.setattr(media, "run", http_boundary)
    args.remove("--offline")
    assert jobs.main(args) == 0
    path, state = job_state(tmp_path)
    assert state["status"] == "COMPLETE_TECHNICAL" and requests == [url]
    candidates = catalogue.read(path / "source_candidates.json")
    [acquired] = candidates["music"]
    assert acquired["url"] == url and Path(acquired["path"]).is_file()
    assert catalogue.sha256(Path(acquired["path"])) == catalogue.sha256(remote)
    qa = catalogue.read(Path(state["delivery"]["video"]).parent / "verification_report.json")
    assert qa["full_decode"] and not qa["quality_flags"]
    assert jobs.main(args) == 0 and requests == [url]


def test_failed_catalogue_lock_does_not_mutate_running_job(tmp_path):
    state_dir = tmp_path / "state"
    state_dir.mkdir()
    job = jobs.Job(tmp_path / "job", options=dict(
        command="create", prompt="Canelo — Reggaeton — 6s", state_dir=str(state_dir),
        request=dict(athlete="Canelo Álvarez", duration_seconds=6)))
    job.state["status"] = "RUNNING"
    job.state["stages"]["render"] = dict(status="RUNNING", attempts=1, process_groups=[])
    job.save()
    report = job.path / "REPORT.txt"
    report.write_text("The owning process is running\n")
    before = {p: catalogue.sha256(p) for p in (job.file, report)}
    with ExitStack() as stack:
        jobs._lock(stack, state_dir / "catalogue.lock")
        assert jobs.main(["resume", str(job.path)]) == 2
    assert {p: catalogue.sha256(p) for p in before} == before


